"""FM1-800: write firmware/src/p800_data.h, the Poly-800 sound's tables (step 4).

  gen_p800.py PAGE.html firmware/src/p800_data.h

The 64 factory programs are read out of the web prototype (its PG array), not typed in by hand; the rest are the
maths tables the integer engine (firmware/src/p800.c) needs, made here with floating point so the firmware has none.
Every number that shapes the sound is the page's own (the page's line is quoted beside it).
"""
import json
import math
import re
import sys
from pathlib import Path

FS = 44100
F0 = 440.0 * 2 ** (-69 / 12)          # MIDI note 0, 8.1758 Hz: pitches below are cents above it
CTL = 32                              # the engine's block


def cents(hz):
    return 1200 * math.log2(hz / F0)


def tm(v, lo, hi):                    # page: function tm(v,lo,hi){return lo*Math.pow(hi/lo,v/31)}
    return lo * (hi / lo) ** (v / 31)


def programs(page):
    m = re.search(r"var PG=(\[.*?\n\]),pc=-1;", page, re.S)
    if not m:
        raise SystemExit("PG array not found in the page")
    pg = json.loads(m.group(1).replace("'", '"'))
    if len(pg) != 64:
        raise SystemExit(f"{len(pg)} programs in the page, expected 64")
    return sorted(pg, key=lambda g: g[0])          # page: PG.sort(function(a,b){return a[0]-b[0]})


# the page's control defaults (its G array), used where a program says nothing (null)
DCO_DEF = [2, 2, 0, 1, 0, 0, 31]                   # octave Mid, Saw, 8', level 31 (dcoSpec(1))
DCO2_DEF = [2, 2, 0, 1, 0, 0, 24, 0, 1]            # level 24, interval 0, detune 1
DEG_DEF = [2, 12, 24, 12, 20, 10]
DEG3_DEF = [0, 14, 16, 14, 6, 12]


def prog_c(g):
    num, name, d1, mode, d2, nz, vcf, ch, e1, e2, e3, mg = g
    d1 = d1 or DCO_DEF
    d2 = d2 or DCO2_DEF

    def dco(a):    # page ld: C['o'+n](a[0]-1); C['w'+n](a[1]===2?0:1); footages a[2..5]; level a[6]
        return "{%d, %d, {%d, %d, %d, %d}, %d}" % (a[0] - 1, 1 if a[1] == 2 else 0, *a[2:6], a[6])

    co, rs, kt, ep, ei, tr = vcf                   # page: ep (v===2?0:1), tr v-1
    degs = ", ".join("{%s}" % ", ".join(map(str, d)) for d in (e1 or DEG_DEF, e2 or DEG_DEF, e3 or DEG3_DEF))
    return ('    {%d, "%s", %d, {%s, %s}, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, {%s}, {%d, %d, %d, %d}},'
            % (num, name.upper(), mode - 1, dco(d1), dco(d2), d2[7], d2[8], nz, co, rs, kt,
               0 if ep == 2 else 1, ei, tr - 1, ch, degs, *mg))


def q(x, bits):
    return int(round(x * (1 << bits)))


def table(name, ctype, vals, per=8):
    rows = [", ".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_p800.py PAGE.html OUT.h")
    pg = programs(Path(sys.argv[1]).read_text(encoding="utf-8"))
    o = []
    o.append("/* SPDX-License-Identifier: GPL-3.0-only */\n/* Generated by tools/poly800_ref/gen_p800.py from the "
             "Poly-800 web prototype: do not edit. */\n")
    o.append(f"#define P800_FS {FS}\n#define P800_NPROG 64\n")

    # ---- programs
    o.append("static const p800_prog_t P800_PROGS[P800_NPROG] = {   /* the page's PG, sorted by number */")
    o += [prog_c(g) for g in pg]
    o.append("};\n")

    # ---- Felucca's PRESETS list (step 5, until FM1-800 has its own screen): the names in 12 characters, as Felucca's
    ab = [("WITH CHIFF", "CHIFF"), ("SQUARE WAVE", "SQUARE"), ("SYNTHICHORD", "SYNCHORD"), ("ACOUSTIC", "AC"),
          ("PERCUSSIVE", "PERC"), ("PERC.", "PERC"), ("SYNTHE", "SYN"), ("ENSEMBLE", "ENS"), ("CRESCENDO", "CRESC"),
          ("MANUAL", "MAN"), ("REVERSE", "REV"), ("DOUBLE", "2X"), ("TONGUED", "TONG"), ("SCIENCE", "SCI"),
          ("BRIGHT", "BRT"), ("FLUTE/BRASS", "FLT/BRS"), ("STRINGS", "STRS"), ("BRASS IN 5THS", "BRASS 5THS"),
          ("RESONANT", "RESO"), ("BOWED", "BOW"), ("TRILLING", "TRILL"), ("CRESC", "CRES"), ("ORGAN", "ORG"),
          ("PERC PIPE", "PRC PIPE"), ("UPPER MAN", "UPPER"), ("LOWER MAN", "LOWER")]
    short = []
    for g in pg:
        n = g[1].upper()
        for a, b in ab:
            if len(n) > 12:
                n = n.replace(a, b)
        short.append(n[:12].rstrip())
    o.append("/* Felucca's PRESETS list (step 5): the names in Felucca's 12 characters */")
    # .. and their categories for its LIST filter (category.c letters: B L P U K D F O), from the names
    def cat(n):
        n = n.upper()
        for keys, c in ((("BASS",), "B"), (("STRINGS", "CELLOS", "VIOLAS", "SWEEP", "SYNTHANELLI", "SYNTHICHORD", "ENSEMBLE",
                                            "LAMBDA", "OB CROSS", "SYNFUL", "LUNAR"), "P"),
                        (("PIANO", "ORGAN", "VIBES", "ACCORDION", "KEYS", "GUITAR", "HARP", "PIPE"), "K"),
                        (("STEEL DRUMS",), "U"), (("JET", "HELICOPTER", "UFO", "BLACK HOLE", "WET ONES", "WHO ME"), "F"),
                        (("BRASS", "LEAD", "FLUTE", "SAXO", "1999", "SYNTHE"), "L")):
            if any(k in n for k in keys):
                return c
        return "O"
    o.append('#define P800_CATS "' + "".join(cat(g[1]) for g in pg) + '"   /* category.c PRESET_CAT */')
    o.append("#define P800_FELUCCA_PRESETS " + ", ".join('{.name = "%s"}' % n for n in short) + "\n")

    # ---- pitch: phase increment of cents c above note 0, octave 10 (shifted down for the octave)
    inc_c = [q(F0 / FS * 2 ** (c / 1200) * 2 ** 10, 32) for c in range(1201)]
    assert max(inc_c) < 2 ** 32
    o.append("/* phase increment (2^32 = one cycle a sample) of 2^(10 + c / 1200) x note 0, c = 0..1200 */")
    o.append(table("P800_INC_C", "uint32_t", inc_c))

    # ---- sine for the LFOs: Q15, 1024 points + 1
    o.append(table("P800_SIN", "int16_t", [q(math.sin(2 * math.pi * i / 1024), 15) if i % 256 else
                                           [0, 32767, 0, -32767, 0][i // 256] for i in range(1025)]))

    # ---- filter: g = tan(pi f / fs), Q16, every 16 cents from note 0 up to just under Nyquist (clamped at 64)
    step = 16
    top = cents(FS / 2)
    gt = []
    c = 0
    while c <= top + step:
        f = F0 * 2 ** (c / 1200)
        gt.append(min(q(math.tan(math.pi * min(f, FS / 2 * 0.99) / FS), 16), 64 << 16))
        c += step
    o.append(f"#define P800_G_STEP {step}\n#define P800_NYQ_CENTS {int(top)}   /* {FS // 2} Hz */")
    o.append("/* g = tan(pi f / fs) of the TPT state-variable filter, Q16, f every P800_G_STEP cents above note 0 */")
    o.append(table("P800_G", "uint32_t", gt))

    # Chrome's own biquad (direct form, RBJ): 1 - cos w0 and sin w0, Q31, on the same steps
    omc, sw = [], []
    c = 0
    while c <= top + step:
        w0 = 2 * math.pi * min(F0 * 2 ** (c / 1200), FS / 2) / FS
        omc.append(min(q(1 - math.cos(w0), 30), 2 << 30))
        sw.append(q(math.sin(w0), 30))
        c += step
    o.append("/* direct-form biquad (Chrome's): 1 - cos w0 and sin w0, Q30, every P800_G_STEP cents */")
    o.append(table("P800_OMC", "uint32_t", omc))
    o.append(table("P800_SINW", "int32_t", sw))

    # cutoff: page function hz(v){return 40*Math.pow(2,v/99*9)}; min(...,18000)
    o.append(table("P800_CO_CENTS", "int16_t", [round(cents(40 * 2 ** (v / 99 * 9))) for v in range(100)], 10))
    o.append(f"#define P800_CAP_CENTS {round(cents(18000))}   /* page: Math.min(..., 18000) */")
    # high-pass add-on: page N.hp.frequency.value=P.hp?40*Math.pow(2,P.hc/99*8):10
    o.append(table("P800_HC_CENTS", "int16_t", [round(cents(40 * 2 ** (v / 99 * 8))) for v in range(100)], 10))
    o.append(f"#define P800_HP_OFF_CENTS {round(cents(10))}   /* 10 Hz: the high-pass is always in the chain */")
    # phaser allpasses: page ap.frequency.value=350*Math.pow(1.5,k)
    o.append(table("P800_AP_CENTS", "int16_t", [round(cents(350 * 1.5 ** k)) for k in range(6)]))

    # damping k = 1 / Q, Q28. Chrome: lowpass / highpass take Q in dB (linear Q = 10^(dB/20)); allpass a linear Q
    o.append("/* TPT damping k = 1 / Q, Q28. Chrome's lowpass and highpass Q is in dB (Q = 10^(dB/20)) */")
    o.append(table("P800_K_LP1", "int32_t", [q(10 ** (-(0.6 + rs / 15 * 16) / 20), 28) for rs in range(16)]))
    o.append(f"#define P800_K_LP2 {q(10 ** (-0.7 / 20), 28)}   /* page N.f2.Q.value=.7 */")
    o.append(f"#define P800_K_HP {q(10 ** (-0.7 / 20), 28)}    /* page N.hp.Q.value=.7 */")
    o.append(f"#define P800_K_AP {q(1 / 0.5, 28)}   /* page ap.Q.value=.5 (allpass: a linear Q) */")

    # Chrome's own shelves, direct form (RBJ, S = 1): b0 b1 b2 a1 a2, normalised by a0, Q29
    def shelf(f0, gain, high):
        A = 10 ** (gain / 40)
        w0 = 2 * math.pi * f0 / FS
        cw, al = math.cos(w0), math.sin(w0) / 2 * math.sqrt(2)
        sa = 2 * math.sqrt(A) * al
        if not high:
            b = [A * ((A + 1) - (A - 1) * cw + sa), 2 * A * ((A - 1) - (A + 1) * cw), A * ((A + 1) - (A - 1) * cw - sa)]
            a = [(A + 1) + (A - 1) * cw + sa, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - sa]
        else:
            b = [A * ((A + 1) + (A - 1) * cw + sa), -2 * A * ((A - 1) + (A + 1) * cw), A * ((A + 1) + (A - 1) * cw - sa)]
            a = [(A + 1) - (A - 1) * cw + sa, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - sa]
        return [q(x / a[0], 29) for x in (b[0], b[1], b[2], a[1], a[2])]
    o.append("/* the shelves, direct form as Chrome's (RBJ, S = 1): b0 b1 b2 a1 a2 / a0, Q29 */")
    o.append(table("P800_LS", "int32_t", shelf(220, -5, False)))    # page N.ls lowshelf 220 Hz -5 dB
    o.append(table("P800_HS", "int32_t", shelf(6000, 3, True)))     # page N.hs highshelf 6000 Hz +3 dB

    # ---- envelopes (page stage(): linear ramps; relp(): setTargetAtTime(0,t,tm(r,.01,5)/4))
    o.append("/* DEG: per-sample rates (Q30 of full scale) of the linear stages, and the release's per-block factor */")
    o.append(table("P800_ATK", "int32_t", [max(1, q(1 / (tm(v, .003, 16) * FS), 30)) for v in range(32)]))
    o.append(table("P800_DEC", "int32_t", [max(1, q(1 / (tm(v, .01, 16) * FS), 30)) for v in range(32)]))
    o.append(table("P800_REL", "int32_t", [q(math.exp(-CTL / (tm(v, .01, 5) / 4 * FS)), 30) for v in range(32)]))
    # page off(): v.until=t+rt*1.5+.1, the oscillators stop there
    o.append(table("P800_REL_END", "int32_t", [round((tm(v, .01, 5) * 1.5 + .1) * FS) for v in range(32)]))
    o.append(f"#define P800_KILL {q(math.exp(-CTL / (.005 * FS)), 30)}   /* page kill(): setTargetAtTime(0,t,.005) */")
    o.append(f"#define P800_KILL_END {round(.05 * FS)}   /* .. o.stop(t+.05) */")
    o.append(f"#define P800_ENV_START {q(.0001, 30)}   /* page stage(): setValueAtTime(0.0001,t) */")

    # ---- LFOs: phase increments
    lfo = lambda hz: q(hz / FS, 32)
    o.append(table("P800_MG_INC", "uint32_t", [lfo(.05 * 600 ** (v / 15)) for v in range(16)]))   # page .05*600^(mf/15)
    o.append(table("P800_PH_INC", "uint32_t", [lfo(.02 * 300 ** (v / 10)) for v in range(11)]))   # page .02*300^(pr/10)
    o.append(f"#define P800_CH_INC_L {lfo(.5)}   /* page chorus LFOs .5 and .83 Hz */\n#define P800_CH_INC_R {lfo(.83)}")
    o.append(f"#define P800_CH_D_L {round(.013 * FS * 1024)}   /* page delays .013 and .017 s, swept .004 s (Q10 samples) */\n"
             f"#define P800_CH_D_R {round(.017 * FS * 1024)}\n#define P800_CH_DEPTH8 {round(.004 * FS * 1024 / 8)}")
    o.append(f"#define P800_WOB_INC0 {lfo(.15)}   /* page age wobble .15+Math.random()*.5 Hz */\n"
             f"#define P800_WOB_INCR {lfo(.5)}")
    o.append("/* the MG's delay in blocks: page dl=P.md/15*2 (s) */")
    o.append(table("P800_MGDLY", "int16_t", [round(v / 15 * 2 * FS / CTL) for v in range(16)]))
    o.append(f"#define P800_MGFADE_BLKS {round(.4 * FS / CTL)}   /* .. then a .4 s ramp */")
    # Chrome's square: its band-limited table is normalised to a peak of 1 (Gibbs), so the flat part is 0.848
    o.append(f"#define P800_SQ_AMP {q(1 / 1.17898, 16)}   /* Chrome's square: plateau 1 / 1.17898 (measured 0.848) */")

    Path(sys.argv[2]).write_text("\n".join(o) + "\n", encoding="utf-8")
    print(f"{len(pg)} programs, tables -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
